"""Write docs/methods_text.md (manuscript Methods for the MD) from what was actually built and configured.

    python prep/methods_text.py

Every number comes from systems/*/provenance.yaml, receptor/receptor_prep.yaml, mdp/*.mdp, analysis/*.in or
prep/systems.yaml, so the Methods cannot drift from the simulations. Re-run after any change to those files.
"""
import re
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
POSE_LABEL = {"glide": "Glide XP", "autodock": "AutoDock4"}


def mdp(name):
    out = {}
    for line in open(ROOT / "mdp" / f"{name}.mdp"):
        line = line.split(";")[0].strip()
        if "=" in line:
            k, v = (s.strip() for s in line.split("=", 1))
            out[k.replace("_", "-")] = v
    return out


def ns(m):
    return float(m["nsteps"]) * float(m["dt"]) / 1000


def mmpbsa(name):
    txt = (ROOT / "analysis" / name).read_text()
    return {k: v.strip().strip('"') for k, v in re.findall(r"^\s*(\w+)\s*=\s*([^,#\n]+)", txt, flags=re.M)}


def rng(vals, fmt="{:,}"):
    lo, hi = min(vals), max(vals)
    return fmt.format(lo) if lo == hi else f"{fmt.format(lo)}–{fmt.format(hi)}"


def main():
    cfg = yaml.safe_load(open(ROOT / "prep" / "systems.yaml"))
    rec = yaml.safe_load(open(ROOT / "receptor" / "receptor_prep.yaml"))
    provs = {n: yaml.safe_load(open(p)) for n in cfg["systems"]
             if (p := ROOT / "systems" / n / "provenance.yaml").exists()}
    missing = [n for n in cfg["systems"] if n not in provs]
    poses = [p for pv in provs.values() for p in pv["poses"].values()]
    atoms = [p["system"]["atoms"] for p in poses]
    waters = [p["system"]["waters"] for p in poses]
    pairs = [p["salt_pairs_added"] for p in poses]
    box = [p["system"]["box"]["a_A"] for p in poses]
    em, nvt, npt, md = mdp("em"), mdp("nvt"), mdp("npt"), mdp("md")
    steps = [mdp(f"npt_posres_{k}") for k in (1000, 500, 100, 10)]
    gb, pb = mmpbsa("mmpbsa_gb.in"), mmpbsa("mmpbsa_pb.in")
    n_rep = cfg["replicas"]
    frames_per_rep = (int(gb["endframe"]) - int(gb["startframe"]) + 1) // int(gb["interval"])
    frame_ps = float(md["nstxout-compressed"]) * float(md["dt"])
    first_ns = (int(gb["startframe"]) - 1) * frame_ps / 1000
    ligs = [pv["ligand"] for pv in provs.values() if "ligand" in pv]
    for l in ligs:          # "decoy (negative control): <IUPAC name>" -> "decoy (negative control, PubChem CID …)"
        short = l["name"].split(":")[0]
        l["short"] = short if short == l["name"] else f"{short[:-1]}, PubChem CID {l['pubchem_cid']})"
    stereo_fixed = sorted({pv["ligand"]["short"] for pv in provs.values() if "ligand" in pv
                           for p in pv["poses"].values() if p["pose"]["heavy_rmsd_A"] > 0})
    run = {n: [p for p in cfg["systems"][n]["poses"] if p["replicas"]] for n in provs}   # poses actually simulated
    split = "; ".join(f"{pv['ligand']['short'].split(' (')[0]} replicas were split "
                      + " and ".join(f"{p['replicas']} from the {POSE_LABEL.get(p['kind'], p['kind'])} pose"
                                     for p in run[n])
                      for n, pv in provs.items() if len(run[n]) > 1)
    split = f" ({split})" if split else ""
    his524 = rec["protonation"]["his524_state"]
    posres_fc = ", ".join(re.search(r"POSRES_FC=(\d+)", s["define"]).group(1) for s in steps)
    text = f"""# Methods — Molecular dynamics simulations (generated by prep/methods_text.py; do not edit by hand)

**Receptor preparation.** The ERα ligand-binding domain was taken from PDB 5WGD (chain A, 1.80 Å) together with
the bound SRC2 coactivator peptide (chain {rec['src2_peptide']['chain']}, {rec['src2_peptide']['sequence']}). The
engineered Y537S mutation was reverted to wild type and missing side-chain atoms were rebuilt with PDBFixer; the
unresolved loop {rec['loop_graft']['residues']} was grafted from a SWISS-MODEL model built on the same template.
Chain A was capped with acetyl and N-methylamide groups ({rec['output']['chain_A']}); crystal waters were removed.
Protonation states at pH {cfg['ph']} were assigned with PDB2PQR/PROPKA3 with hydrogen-bond optimisation in the
presence of crystal estradiol; His524 was modelled as {his524} (Nδ1 accepting the hydrogen bond of the
estradiol 17β-hydroxyl).

**Ligands.** {len(ligs)} ligands were simulated: {', '.join(l['short'] for l in ligs)}, plus the apo receptor.
Each ligand was modelled in its dominant microstate at pH {cfg['ph']}
({', '.join(f"{l['short'].split(' (')[0]} {l['formal_charge']:+d}" for l in ligs if l['formal_charge'])}; others neutral) with
explicitly defined stereochemistry, verified by CIP labels. Starting poses were taken from Glide XP docking
into one rigid receptor model: for each ligand, the best-scoring pose with the intended stereochemistry across all
Glide XP runs (estradiol from its crystal pose instead; PaPE-1, which was not docked with Glide, from its
AutoDock4 rank-1 pose; the decoy, from its supplied pose); where no docked pose had the intended configuration at
a stereocentre ({', '.join(stereo_fixed) or 'none'}), the intended stereoisomer was rebuilt into that pose
(heavy-atom RMSD to the docked pose ≤ {max(p['pose']['heavy_rmsd_A'] for p in poses if 'pose' in p):.2f} Å).
Ligands were described with GAFF2 and AM1-BCC charges computed once per ligand with antechamber/sqm.

**Systems.** The protein was described with ff14SB, water with TIP3P and ions with the Joung–Cheatham parameters.
Each complex was solvated in a truncated octahedron with at least {provs[next(iter(provs))]['solvation']['buffer_A']:.0f} Å
between solute and box edge (a = {rng(box, '{:.1f}')} Å), neutralised with Na⁺/Cl⁻ and brought to 0.15 M NaCl
({rng(pairs)} ion pairs), giving {rng(atoms)} atoms ({rng(waters)} waters). Topologies were built with tleap and
converted to GROMACS format with ParmEd.

**Simulation protocol.** Simulations were run with GROMACS 2026. Hydrogen masses were repartitioned to
{float(md['mass-repartition-factor']) * 1.008:.3f} u by moving mass from the bonded heavy atom (factor {md['mass-repartition-factor']}),
which allows a {float(md['dt']) * 1000:.0f} fs time step ({float(nvt['dt']) * 1000:.0f} fs during NVT heating) with LINCS constraints on
bonds to hydrogen, PME electrostatics ({md['fourierspacing']} nm grid, order {md['pme-order']}) with
{md['rcoulomb']} nm real-space and Lennard-Jones cutoffs and a long-range dispersion correction for energy and
pressure. Temperature was kept at {md['ref-t']} K with the V-rescale thermostat (τ = {md['tau-t']} ps) and pressure
at {md['ref-p']} bar with the C-rescale barostat (τ = {md['tau-p']} ps). Each system was minimised (steepest descent
to Fmax < {float(em['emtol']):.0f} kJ mol⁻¹ nm⁻¹), equilibrated for {ns(nvt) * 1000:.0f} ps under NVT and then under
NPT with heavy-atom position restraints of {posres_fc} kJ mol⁻¹ nm⁻² ({ns(steps[0]) * 1000:.0f} ps
each), followed by {ns(npt):.0f} ns of unrestrained NPT. Production runs of {ns(md):.0f} ns were performed in
{n_rep} independent replicas per system, each with its own random velocity seed{split}. Coordinates of the receptor–ligand complex were saved every
{float(md['nstxout-compressed']) * float(md['dt']):.0f} ps. The first {first_ns:.0f} ns of each replica were excluded from
analysis.

**Analysis and statistics.** Ligand heavy-atom RMSD was computed after fitting on pocket Cα atoms; pose
retention is the fraction of frames within 2.0 Å of the starting pose. Hydrogen-bond and contact occupancies,
backbone RMSD and Cα RMSF were computed per replica. All quantities are reported as the mean ± SEM over the
{n_rep} replicas (each replica one independent sample), with block averaging used to confirm convergence within
replicas.

**End-point energies.** MM/GBSA energies were computed with gmx_MMPBSA (single-trajectory protocol) on
{frames_per_rep} frames per replica ({frames_per_rep * n_rep} per system) using the GB-neck2 model (igb =
{gb['igb']}, mbondi3 radii), {gb['saltcon']} M salt and external dielectric {gb['extdiel']}; because the result
depends on the solute dielectric, calculations were repeated at ε_in = 1, 2 and 4, and Poisson–Boltzmann
calculations (ε_in = 2, {pb['istrng']} M) were used as a cross-check. Per-residue decomposition was performed for
residues within 6 Å of the ligand. Conformational entropy was not estimated. These energies are used only to rank
complexes relative to estradiol and are not interpreted as binding free energies or affinities.
"""
    if missing:
        text += f"\n> **Incomplete:** no provenance yet for {', '.join(missing)}.\n"
    (ROOT / "docs" / "methods_text.md").write_text(text)
    print(f"docs/methods_text.md written from {len(provs)} systems, {len(poses)} poses")


if __name__ == "__main__":
    main()
